import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const requireTools = createRequire(path.join(path.resolve(process.argv[2]), 'package.json'));
const { chromium } = requireTools('playwright');
const output = path.resolve(process.argv[3]);
const origin = process.argv[4];
const executablePath = process.argv[5];
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(executablePath ? { executablePath } : {}) });
const observations = [];
const errors = [];
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const outgoing = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => {
  const url = new URL(request.url());
  if (['http:', 'https:'].includes(url.protocol) && url.origin !== new URL(origin).origin) outgoing.push(url.href);
});
try {
  await page.goto(origin);
  await page.getByTestId('feedback-entry').waitFor();
  const box = await page.getByTestId('feedback-entry').boundingBox();
  assert.ok(box.y > 500, '入口应处于真实侧栏下部');
  await page.screenshot({ path: path.join(output, '01-entry.png') });
  await page.getByTestId('feedback-entry').click();
  await page.getByRole('button', {name:'直接提交', exact:true}).click();
  await page.getByRole('alert').filter({hasText:'请填写标题和问题描述'}).waitFor();
  await page.getByLabel('问题标题', {exact:true}).fill('预览哨兵：工具调用后没有响应');
  await page.getByLabel('问题描述', {exact:true}).fill('反馈内容哨兵：操作后等待一分钟，页面没有新消息。');
  await page.screenshot({ path: path.join(output, '02-form.png') });
  await page.getByRole('button', {name:'直接提交', exact:true}).click();
  assert.match(await page.getByLabel('报告正文', {exact:true}).inputValue(), /反馈内容哨兵/);
  assert.equal(await page.getByRole('button', {name:'确认上传（模拟）',exact:true}).isDisabled(), true);
  await page.getByLabel('确认上传内容').check();
  await page.getByLabel('报告正文', {exact:true}).fill('人工修改后的正文哨兵');
  assert.equal(await page.getByLabel('确认上传内容').isChecked(), false);
  await page.getByLabel('确认上传内容').check();
  await page.getByRole('button', {name:'确认上传（模拟）',exact:true}).click();
  await page.getByRole('heading', {name:'模拟提交完成'}).waitFor();
  observations.push('普通路径：真实输入进入报告，未确认禁发，修改使确认失效，模拟结果明确');
  await page.getByRole('button', {name:'完成',exact:true}).click();
  await page.getByTestId('feedback-entry').click();
  await page.getByRole('button', {name:/分析并上传/}).click();
  await page.screenshot({ path: path.join(output, '03-scope.png') });
  assert.equal(await page.getByRole('button', {name:'开始分析',exact:true}).isDisabled(), true);
  await page.getByLabel('允许分析材料').check();
  await page.getByLabel('模拟分析失败').check();
  await page.getByRole('button', {name:'开始分析',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'Agent Client 暂时不可用'}).waitFor();
  await page.getByLabel('模拟分析失败').uncheck();
  await page.getByRole('button', {name:'开始分析',exact:true}).click();
  await page.getByLabel('报告正文', {exact:true}).waitFor();
  assert.match(await page.getByLabel('报告正文', {exact:true}).inputValue(), /反馈内容哨兵/);
  assert.match(await page.getByLabel('报告正文', {exact:true}).inputValue(), /未验证事项/);
  await page.locator('input[type=file]').setInputFiles({name:'示例截图.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aX1sAAAAASUVORK5CYII=','base64')});
  await page.getByLabel('确认上传内容').check();
  assert.equal(await page.getByRole('button', {name:'确认上传（模拟）',exact:true}).isDisabled(), true);
  await page.getByText('我已检查图片中的敏感信息', {exact:true}).click();
  await page.getByLabel('确认上传内容').check();
  assert.equal(await page.getByRole('button', {name:'确认上传（模拟）',exact:true}).isEnabled(), true);
  await page.getByLabel('提交目标').selectOption({label:'GitLab · 示例内网项目 · 私有'});
  assert.equal(await page.getByLabel('确认上传内容').isChecked(), false);
  await page.screenshot({ path: path.join(output, '04-review.png') });
  observations.push('分析路径：材料确认、失败恢复、报告保留原始描述、图片独立检查、换目标撤销确认');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(output,'05-narrow.png')});
  const dialogBox = await page.getByRole('dialog').boundingBox();
  assert.ok(dialogBox.x >= 0 && dialogBox.width <= 390);
  await page.getByRole('button',{name:'关闭问题反馈',exact:true}).click();
  await page.goto(origin + '?classic=1');
  await page.getByTestId('feedback-entry').click();
  await page.getByLabel('问题标题',{exact:true}).waitFor();
  await page.screenshot({path:path.join(output,'06-classic.png')});
  observations.push('窄屏及经典侧栏：真实入口可达，表单无水平越界');
  assert.deepEqual(errors, [], '浏览器未捕获异常');
  assert.deepEqual(outgoing, [], '体验稿没有向外部发起浏览器请求');
} finally {
  await browser.close();
  await writeFile(path.join(output,'checks.json'),JSON.stringify({kind:'synthetic-ui-experience-only',observations,errors,outgoing,productionAcceptance:false,browserClosed:!browser.isConnected()},null,2));
}
console.log(JSON.stringify({checks:observations.length,errors:errors.length,outgoing:outgoing.length,browserClosed:!browser.isConnected()}));
